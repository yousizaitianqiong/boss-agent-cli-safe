"""Browser-based compatibility client for user-triggered browser flows.

stoken can be generated by the browser's JS environment when a user-initiated
login flow needs compatibility help. Low-Risk Assistance Mode blocks sensitive
automation such as outreach, bulk actions, risk-control retries, and candidate
personal-data workflows before they reach this client.

Supports two modes:
  1. CDP mode: connects to user's existing Chrome via DevTools Protocol
  2. Patchright mode (fallback): launches a headless Chromium instance
"""

import os
import sys
import time
from pathlib import Path
from types import TracebackType
from typing import Any, cast
from urllib.parse import urlparse

from patchright.sync_api import TimeoutError as PatchrightTimeoutError
from patchright.sync_api import sync_playwright

from boss_agent_cli.api import endpoints
from boss_agent_cli.api.throttle import RequestThrottle
from boss_agent_cli.auth.browser import _DEFAULT_CDP_URL as CDP_DEFAULT_URL

HOME_URL = "https://www.zhipin.com/"
_ZHIPIN_HOST = "zhipin.com"
_SAFE_STRICT_CDP_ENV = "BOSS_SAFE_STRICT_CDP_URL"
_SECURITY_URL_MARKERS = ("security-check", "captcha", "verify", "validate")
_ACCOUNT_RISK_URL_MARKERS = ("account-risk", "account_risk", "account/abnormal")


def _is_zhipin_url(url: str) -> bool:
	"""精确 hostname 校验：仅 zhipin.com 或其子域名视为 BOSS 直聘页面。

	刻意不用 ``"zhipin.com" in url`` 子串判断——伪造 host（如
	``zhipin.com.evil.example``）或带该域名的查询串都能骗过子串检查
	（CodeQL ``py/incomplete-url-substring-sanitization``）。
	"""
	host = urlparse(url).hostname
	if host is None:
		return False
	host = host.rstrip(".").lower()
	return host == _ZHIPIN_HOST or host.endswith(f".{_ZHIPIN_HOST}")


def _find_reusable_zhipin_page(context: Any) -> Any | None:
	"""在用户 context 已打开的页面里找第一个 zhipin 页复用，找不到返回 None。"""
	for page in getattr(context, "pages", None) or []:
		if _is_zhipin_url(getattr(page, "url", "")):
			return page
	return None


def _page_challenge_code(url: str) -> str | None:
	"""仅按 URL 的稳定标识识别人工安全检查，不读取页面正文。"""
	lower = url.lower()
	if any(marker in lower for marker in _ACCOUNT_RISK_URL_MARKERS):
		return "ACCOUNT_RISK"
	if any(marker in lower for marker in _SECURITY_URL_MARKERS):
		return "CAPTCHA"
	return None


